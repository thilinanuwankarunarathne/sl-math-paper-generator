# 3) සංඛ්‍යාත ව්‍යාප්තිය
def L_freq(r, d):
    w, s0 = r.choice([5, 10]), r.choice([0, 10, 20, 30])
    while True:
        fs = [r.randint(2, 15) for _ in range(5)]
        if fs.count(max(fs)) == 1:
            break
    cls = [f"{s0+i*w} - {s0+(i+1)*w}" for i in range(5)]
    mid = [sp.Rational(2 * s0 + (2 * i + 1) * w, 2) for i in range(5)]
    sf, sfx = sum(fs), sum(f * m for f, m in zip(fs, mid))
    k = fs.index(max(fs))
    c = ("පන්තියක සිසුන්ගේ ලකුණු ව්‍යාප්තිය පහත වගුවේ දැක්වේ.\n\n" +
         table(["ලකුණු ප්‍රාන්තරය"] + cls, [["සිසුන් ගණන ($f$)"] + fs]) +
         "\n\n(අ) පන්තියේ මුළු සිසුන් ගණන සොයන්න.\n\n(ආ) මාතෘ පන්තිය (modal class) ලියන්න.\n\n"
         "(ඉ) පන්ති මධ්‍ය අගයන් භාවිතයෙන් ලකුණුවල මධ්‍යනය සොයන්න.\n\n"
         "(ඊ) මාතෘ පන්තියේ සිසුන් මුළු සිසුන්ගෙන් ප්‍රතිශතයක් ලෙස (දශම 1කට) සොයන්න.")
    return mkL(c, [
        (f"(අ) $\\sum f={'+'.join(map(str, fs))}={sf}$", 1),
        (f"(ආ) වැඩිම සංඛ්‍යාතය ${max(fs)}$ බැවින් මාතෘ පන්තිය ${cls[k]}$", 1),
        ("(ඉ) පන්ති මධ්‍ය අගයන්: " + ", ".join(L(m) for m in mid), 1),
        (f"$\\sum fx={L(sfx)}$", 2), (f"මධ්‍යනය $={F(L(sfx), sf)}={L(sp.Rational(sfx, sf))}$", 2),
        (f"(ඊ) ${F(max(fs), sf)}\\times100={max(fs)*100/sf:.1f}\\%$", 3)])


